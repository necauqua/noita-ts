const findMagicNumber = <K extends MagicNumbers>(name: K) => {
  // only place with mov EDX <magic number string> is GetMagicNumber,
  //  SetMagicNumbers has pushes
  const [a, b, c, d] = ffi.le32(ffi.locateString(name));
  const movStr = ffi.text.scanAll(
    [ 0xBA, a, b, c, d ],
    { name: `mov EDX "${name}"` },
  );
  const pushMagic = ffi.scan([0x68], { at: movStr + 5 });
  const addr = ffi.cast("uint32_t*", pushMagic + 1)[0];

  return ffi.cast<Ptr<MagicNumberTypes[K]>>(`${magicNumberTypes[name]}*`, addr);
};

const magicNumbers = setmetatable(
  {},
  {
    __metatable: {}, // freeze
    __index: (self: any, key: MagicNumbers) => {
      const ptr = findMagicNumber(key);
      self[key] = ptr;
      return ptr;
    }
  }) as unknown as { [K in MagicNumbers]: Ptr<MagicNumberTypes[K]> }; // setmetatable type is confused :(

